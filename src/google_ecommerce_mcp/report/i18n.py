def norm_lang(lang: Any) -> str:
    """'fr' or 'en'; anything else is the default language."""
    return lang if lang in LANGS else DEFAULT_LANG


def tr(lang: str, key: str, **kwargs: Any) -> str:
    """The plain-text template ``key`` in ``lang`` formatted with ``kwargs`` (not HTML-escaped)."""
    template = STRINGS.get(norm_lang(lang), {}).get(key) or STRINGS[DEFAULT_LANG].get(key) or key
    try:
        return template.format(**kwargs)
    except (KeyError, IndexError, ValueError):
        return template


def _is_num(value: Any) -> bool:
    return _numbers_is_num(value)


def fmt_number(value: Any, digits: int = 0, lang: str = DEFAULT_LANG) -> str:
    """Grouped number with ``digits`` decimals in the language's format; "—" when not a number."""
    if not _is_num(value):
        return "—"
    text = f"{abs(value):,.{digits}f}"
    if norm_lang(lang) == "fr":
        text = text.replace(",", NNBSP).replace(".", ",")
    rounded_zero = float(f"{abs(value):.{digits}f}") == 0
    return (MINUS if value < 0 and not rounded_zero else "") + text


def fmt_int(value: Any, lang: str = DEFAULT_LANG) -> str:
    return fmt_number(value, 0, lang)


def money_digits(value: float) -> int:
    """0 decimals from 1000 or for whole amounts, 1 from 10, else 2 (24 900 €, 145,6 €, 0,76 €)."""
    a = abs(value)
    if a >= 1000 or float(value).is_integer():
        return 0
    return 1 if a >= 10 else 2


def fmt_money(value: Any, currency: str | None, lang: str = DEFAULT_LANG) -> str:
    """Amount with its currency, never converted; "—" when not a number. No currency: the bare number."""
    if not _is_num(value):
        return "—"
    number = fmt_number(value, money_digits(value), lang)
    code = currency.strip().upper() if isinstance(currency, str) and currency.strip() else ""
    if not code:
        return number
    symbol = CURRENCY_SYMBOLS.get(code, code)
    if norm_lang(lang) == "fr":
        return f"{number}{NBSP}{symbol}"
    if symbol == code:
        return f"{number}{NBSP}{code}"
    sign = MINUS if number.startswith(MINUS) else ""
    return f"{sign}{symbol}{number.lstrip(MINUS)}"


def fmt_pct(ratio: Any, digits: int = 1, lang: str = DEFAULT_LANG) -> str:
    """A 0..1 ratio as a percentage ("1,9 %" / "1.9%"); "—" when not a number."""
    if not _is_num(ratio):
        return "—"
    number = fmt_number(ratio * 100, digits, lang)
    return f"{number}{NBSP}%" if norm_lang(lang) == "fr" else f"{number}%"


def fmt_date(d: date | None, lang: str = DEFAULT_LANG) -> str:
    """'1er septembre 2026' / 'September 1, 2026'."""
    if d is None:
        return "—"
    month = MONTHS[norm_lang(lang)][d.month - 1]
    if norm_lang(lang) == "fr":
        return f"{'1er' if d.day == 1 else d.day} {month} {d.year}"
    return f"{month} {d.day}, {d.year}"


def fmt_month(d: date, lang: str = DEFAULT_LANG) -> str:
    """'septembre 2026' / 'September 2026'."""
    return f"{MONTHS[norm_lang(lang)][d.month - 1]} {d.year}"


